"""Real-telemetry benchmark scenarios derived from RCAEval RE2.

Loads the scenario set generated by `scripts/build_rcaeval_dataset.py`
from real chaos-injected failure cases in the RCAEval benchmark (Pham et
al., FSE'26 / WWW'25 / ASE'24; Zenodo DOI 10.5281/zenodo.14590730, MIT
licensed). Each case comes from a real microservice system running on
Kubernetes (Online Boutique, Sock Shop, or Train Ticket) with a fault
injected via chaos tooling and per-second metrics plus container logs
captured around the injection window.

This exists alongside `benchmark_dataset.py`'s hand-authored scenarios,
not instead of them: the authored set is synthetic, so a result that
holds on both is far better evidenced than one resting on templates
alone. Both expose the same scenario dict shape, so the evaluation
pipeline runs over either unchanged.

The same leakage discipline applies here as in `benchmark_dataset.py`:
`observed_symptoms` holds only raw telemetry (metric before/after values
across *every* service in the system, plus real log lines), while
`ground_truth_claims` — derived from RCAEval's own root-cause-service and
fault-type label — is held out for scoring only. Enforced by
`tests/test_rcaeval_dataset.py`.

Regenerate with:
    .venv/bin/python scripts/build_rcaeval_dataset.py --n-cases 25
"""

import json
from pathlib import Path
from typing import Any, Dict, List

_GENERATED_PATH = Path(__file__).with_name("rcaeval_dataset_generated.json")


def load_rcaeval_scenarios() -> List[Dict[str, Any]]:
    """Return the generated RCAEval-derived scenarios.

    Returns an empty list if the generated file is absent, so importing
    this module never breaks an environment that hasn't run the build
    script — callers should check for emptiness rather than assume.
    """
    if not _GENERATED_PATH.exists():
        return []
    return json.loads(_GENERATED_PATH.read_text(encoding="utf-8"))


RCAEVAL_SCENARIOS: List[Dict[str, Any]] = load_rcaeval_scenarios()
